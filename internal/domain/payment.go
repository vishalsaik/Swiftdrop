package domain

import (
	"slices"
	"time"
)

// PaymentRequest is what the order service hands to a PaymentProvider.
// IdempotencyKey is mandatory input, not an afterthought: Core invariant #4
// requires "a payment operation is idempotent for a given order and payment
// key," so the key travels with the request from the start rather than
// being bolted on by a decorator later.
type PaymentRequest struct {
	OrderID         string `json:"orderId"`
	IdempotencyKey  string `json:"idempotencyKey"`
	AmountCents     int64  `json:"amountCents"`
	Currency        string `json:"currency"`
	// PaymentMethodID is the provider token from the client (e.g. Stripe's
	// pm_xxx created by Stripe.js). Empty for cash payments.
	PaymentMethodID string `json:"paymentMethodId"`
}

// PaymentType is how a customer chose to pay for an order. It is chosen
// when the order is created and stored on it, because /pay is a separate
// request that has to know which method to use.
type PaymentType string

const (
	PaymentCard   PaymentType = "card"
	PaymentCash   PaymentType = "cash"
	PaymentWallet PaymentType = "wallet"
)

// PaymentTypes lists every accepted payment type, in display order. It is
// the single source of truth for validation and for error messages.
var PaymentTypes = []PaymentType{PaymentCard, PaymentCash, PaymentWallet}

// Valid reports whether p is one of the accepted payment types.
func (p PaymentType) Valid() bool {
	return slices.Contains(PaymentTypes, p)
}

// MaxPaymentAttempts is how many times an order may be paid for. A decline moves
// the order back to created so the customer can try another method; the last
// allowed decline cancels it instead.
const MaxPaymentAttempts = 3

type PaymentStatus string

const (
	// PaymentProcessing is only ever stored, never returned by a provider: it
	// marks a payment attempt that has been claimed and has no final answer yet.
	PaymentProcessing PaymentStatus = "processing"
	PaymentAuthorized PaymentStatus = "authorized"
	PaymentDeclined   PaymentStatus = "declined"
	PaymentRefunded   PaymentStatus = "refunded"
	// PaymentAbandoned: the attempt was claimed and the provider has no record of
	// it, so no money moved. It is final: the order is open again for a new
	// attempt (or cancelled when the attempts have run out). Stored only.
	PaymentAbandoned PaymentStatus = "abandoned"
	// PaymentNeedsReview: the attempt has had no answer for too long to be settled
	// by itself, and the customer may or may not have been charged. A person looks
	// at it; the provider's answer, if it ever arrives, still settles it. A new
	// attempt is refused meanwhile. Stored only.
	PaymentNeedsReview PaymentStatus = "needs_review"
)

// Unsettled reports whether the payment still waits for an answer from the
// provider: it was claimed and nobody has recorded what became of it.
func (p Payment) Unsettled() bool {
	return p.Status == PaymentProcessing || p.Status == PaymentNeedsReview
}

// OrderStateAfterFailure is where a payment that did not go through leaves its
// order (declined, or abandoned because the provider never saw it): back to
// created, so the customer can try again, unless this was the last attempt.
func (p Payment) OrderStateAfterFailure() OrderState {
	if p.Attempt >= MaxPaymentAttempts {
		return OrderCancelled
	}
	return OrderCreated
}

type PaymentResult struct {
	PaymentID string        `json:"paymentId"`
	Status    PaymentStatus `json:"status"`
	Reason    string        `json:"reason"` // set when Status is PaymentDeclined
}

// LookupRequest asks a provider what became of a payment we claimed, without
// sending the charge again. We do not know the provider's id for it (that is
// exactly what a lost reply loses), so the provider finds it by our own id.
type LookupRequest struct {
	PaymentID   string    // our payment id
	CreatedAt   time.Time // when we claimed it: the provider cannot have it from before
	AmountCents int64
}

// LookupResult is what the provider knows about a payment.
type LookupResult struct {
	// Found is false when the provider has no record of the payment: the charge
	// never reached it, so no money moved.
	Found bool
	// Status is authorized or declined when the provider has a final answer. It
	// is empty when the provider has the payment but has not decided yet.
	Status            PaymentStatus
	ProviderPaymentID string
	Reason            string
}

// Payment is our own record of one payment attempt for an order, kept so a
// retried request can find the attempt instead of starting another one.
// Its ID is generated by us when the attempt is claimed, and is also what we
// send to the provider as the idempotency key.
type Payment struct {
	ID          string        `json:"id"`
	OrderID     string        `json:"orderId"`
	Status      PaymentStatus `json:"status"`
	AmountCents int64         `json:"amountCents"`
	// ProviderPaymentID is the provider's own id for the payment, set when the
	// attempt completes. Empty while processing.
	ProviderPaymentID string `json:"providerPaymentId"`
	// Reason is the decline reason; empty unless the status is declined.
	Reason string `json:"reason"`
	// LeaseExpiresAt is the deadline of the current claim: until then whoever
	// holds the claim is working on the payment and nobody else may touch it,
	// and after it a later request may take the attempt over.
	LeaseExpiresAt time.Time `json:"leaseExpiresAt"`
	CreatedAt      time.Time `json:"createdAt"`
	UpdatedAt      time.Time `json:"updatedAt"`
	// Attempt numbers the order's payments 1, 2, 3 ...: a declined payment can be
	// followed by another, up to MaxPaymentAttempts.
	Attempt int `json:"attempt"`

	// The refund of this payment, a second dimension next to Status: a payment
	// stays authorized forever (the money was taken), and RefundStatus says
	// whether it has been given back. Empty is the same as RefundNone.
	RefundStatus RefundStatus `json:"refundStatus"`
	// RefundID is the provider's id for the refund, set when it is done.
	RefundID string `json:"refundId"`
	// RefundAttempts counts how often a refund was started, to give up after a few.
	RefundAttempts int `json:"refundAttempts"`
	// RefundError is why the last attempt failed, for the person who looks.
	RefundError string `json:"refundError"`
	// RefundLeaseExpiresAt is the deadline of the refund job's claim, like
	// LeaseExpiresAt but for the refund. Nil unless a refund is in progress.
	RefundLeaseExpiresAt *time.Time `json:"refundLeaseExpiresAt,omitempty"`
}

// RefundStatus says where giving the money back stands.
type RefundStatus string

const (
	// RefundNone: nothing has been refunded. Together with an authorized payment
	// on a cancelled order it means a refund is DUE.
	RefundNone RefundStatus = "none"
	// RefundInProgress: the refund job has claimed it and is asking the provider.
	RefundInProgress RefundStatus = "refunding"
	// RefundDone: the provider accepted the refund.
	RefundDone RefundStatus = "refunded"
	// RefundFailed: the job gave up after several attempts. A person must look.
	RefundFailed RefundStatus = "failed"
)

// RefundRequest is what the refund job hands to a Refunder.
type RefundRequest struct {
	PaymentID         string `json:"paymentId"`         // our payment id
	ProviderPaymentID string `json:"providerPaymentId"` // what to refund
	AmountCents       int64  `json:"amountCents"`
	// IdempotencyKey makes a repeated request refund once. It is derived from
	// the payment id, so every attempt for one payment uses the same key.
	IdempotencyKey string `json:"idempotencyKey"`
}

// RefundResult is the provider's acceptance of a refund.
type RefundResult struct {
	RefundID string `json:"refundId"`
}

// PaymentEvent is one line of a payment's history: something that happened to it
// and when. The history is append-only and written by the database itself in the
// same transaction as the change it describes, so it cannot disagree with it.
type PaymentEvent struct {
	ID        int64     `json:"id"`
	PaymentID string    `json:"paymentId"`
	At        time.Time `json:"at"`
	// Kind is what happened: claimed, taken_over, authorized, declined,
	// refund_started, refund_attempt_failed, refunded or refund_failed.
	Kind string `json:"kind"`
	// Detail is a short fact about it (an amount, a provider id, a reason).
	Detail string `json:"detail"`
}
